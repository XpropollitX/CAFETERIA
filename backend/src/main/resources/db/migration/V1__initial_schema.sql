CREATE TABLE roles (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(255)
);

CREATE TABLE usuarios (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    correo VARCHAR(254) NOT NULL UNIQUE,
    telefono VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    id_rol BIGINT NOT NULL REFERENCES roles (id_rol) ON DELETE RESTRICT,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categorias (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE productos (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria BIGINT NOT NULL REFERENCES categorias (id_categoria) ON DELETE RESTRICT,
    nombre VARCHAR(150) NOT NULL,
    descripcion VARCHAR(1000),
    precio NUMERIC(10, 2) NOT NULL CHECK (precio >= 0),
    imagen_url VARCHAR(2048),
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pedidos (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    fecha_pedido TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(30) NOT NULL DEFAULT 'RECIBIDO'
        CHECK (estado IN ('RECIBIDO', 'EN_PREPARACION', 'LISTO', 'ENTREGADO', 'CANCELADO')),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0),
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    observaciones VARCHAR(1000)
);

CREATE TABLE detalle_pedido (
    id_detalle BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedidos (id_pedido) ON DELETE RESTRICT,
    id_producto BIGINT NOT NULL REFERENCES productos (id_producto) ON DELETE RESTRICT,
    cantidad INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal NUMERIC(10, 2) NOT NULL CHECK (subtotal >= 0)
);

CREATE TABLE pagos (
    id_pago BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedidos (id_pedido) ON DELETE RESTRICT,
    metodo_pago VARCHAR(20) NOT NULL CHECK (metodo_pago IN ('EFECTIVO', 'YAPE', 'PLIN')),
    monto NUMERIC(10, 2) NOT NULL CHECK (monto > 0),
    estado_pago VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado_pago IN ('PENDIENTE', 'PAGADO', 'ANULADO')),
    registrado_por BIGINT REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    fecha_pago TIMESTAMPTZ,
    referencia VARCHAR(255)
);

CREATE TABLE historial_estado_pedido (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES pedidos (id_pedido) ON DELETE RESTRICT,
    estado VARCHAR(30) NOT NULL
        CHECK (estado IN ('RECIBIDO', 'EN_PREPARACION', 'LISTO', 'ENTREGADO', 'CANCELADO')),
    id_usuario BIGINT NOT NULL REFERENCES usuarios (id_usuario) ON DELETE RESTRICT,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    observacion VARCHAR(1000)
);

CREATE INDEX idx_usuarios_id_rol ON usuarios (id_rol);
CREATE INDEX idx_productos_id_categoria ON productos (id_categoria);
CREATE INDEX idx_pedidos_id_usuario_fecha ON pedidos (id_usuario, fecha_pedido DESC);
CREATE INDEX idx_pedidos_estado_fecha ON pedidos (estado, fecha_pedido);
CREATE INDEX idx_detalle_pedido_id_pedido ON detalle_pedido (id_pedido);
CREATE INDEX idx_detalle_pedido_id_producto ON detalle_pedido (id_producto);
CREATE INDEX idx_pagos_id_pedido_estado ON pagos (id_pedido, estado_pago);
CREATE INDEX idx_pagos_registrado_por ON pagos (registrado_por);
CREATE INDEX idx_historial_pedido_fecha ON historial_estado_pedido (id_pedido, fecha_cambio);
CREATE INDEX idx_historial_id_usuario ON historial_estado_pedido (id_usuario);

